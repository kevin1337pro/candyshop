 register_post_type( 'candy_withdrawal', array(
  'labels' => array( 'name' => 'Widerrufe', 'singular_name' => 'Widerruf' ), 'public' => false,
  'show_ui' => true, 'show_in_rest' => false, 'show_in_menu' => 'woocommerce', 'supports' => array( 'title', 'editor' ),
  'capabilities' => array( 'edit_post' => 'manage_woocommerce', 'read_post' => 'manage_woocommerce', 'delete_post' => 'manage_woocommerce', 'edit_posts' => 'manage_woocommerce', 'edit_others_posts' => 'manage_woocommerce', 'publish_posts' => 'manage_woocommerce', 'read_private_posts' => 'manage_woocommerce', 'delete_posts' => 'manage_woocommerce', 'create_posts' => 'do_not_allow' ), 'map_meta_cap' => false,
 ) );
} );
function candy_withdrawal_fields( $input ) {
 $values = array();
 foreach ( array( 'name' => 150, 'contract' => 2000, 'email' => 254 ) as $key => $max ) {
  $value = $input[$key] ?? '';
  if ( ! is_string( $value ) || strlen( $value ) > $max * 4 ) { throw new Exception( 'Bitte prüfe die Länge deiner Eingaben.' ); }
  $values[$key] = trim( 'contract' === $key ? sanitize_textarea_field( $value ) : sanitize_text_field( $value ) );
  if ( ! $values[$key] || mb_strlen( $values[$key] ) > $max ) { throw new Exception( 'Bitte fülle alle Felder innerhalb der angegebenen Länge aus.' ); }
 }
 if ( ! is_email( $values['email'] ) ) { throw new Exception( 'Bitte gib eine gültige E-Mail-Adresse für die Bestätigung ein.' ); }
 return $values;
}
function candy_record_withdrawal( $values, $token ) {
 // Token is generated by this form and signed with a server secret. A repeat
 // submission returns the same receipt instead of sending duplicate emails.
 if ( ! preg_match( '/^[a-f0-9-]{36}$/', $token ) ) { throw new Exception( 'Bitte öffne das Formular erneut.' ); }
 $existing = get_posts( array( 'post_type' => 'candy_withdrawal', 'post_status' => 'private', 'meta_key' => '_candy_token', 'meta_value' => $token, 'numberposts' => 1 ) );
 if ( $existing ) { return $existing[0]->ID; }
 $time = wp_date( 'd.m.Y H:i:s T' );
 $text = "Eingangsbestätigung Ihres Widerrufs\n\nHiermit widerrufe ich den folgenden Vertrag bzw. die angegebenen Artikel.\n\nName: " . $values['name'] . "\nVertrag / Artikel: " . $values['contract'] . "\nE-Mail für die Bestätigung: " . $values['email'] . "\nEingegangen: " . $time . "\n\nDiese Nachricht bestätigt den Eingang Ihrer Erklärung. Eine etwaige Rückzahlung wird gesondert bearbeitet.";
 $id = wp_insert_post( array( 'post_type' => 'candy_withdrawal', 'post_status' => 'private', 'post_title' => 'Widerruf vom ' . $time, 'post_content' => $text, 'meta_input' => array( '_candy_token' => $token, '_candy_receipt_email' => $values['email'], '_candy_receipt_time' => $time, '_candy_customer_sent' => 'no', '_candy_merchant_sent' => 'no' ) ), true );
 if ( is_wp_error( $id ) || ! $id ) { throw new Exception( 'Dein Widerruf konnte nicht gespeichert werden. Bitte versuche es erneut oder nutze die Kontaktadresse im Impressum.' ); }
 candy_deliver_withdrawal( $id );
 return $id;
}
function candy_deliver_withdrawal( $id ) {
 $post = get_post( $id ); if ( ! $post || 'candy_withdrawal' !== $post->post_type ) { return; }
 foreach ( array( 'customer' => get_post_meta( $id, '_candy_receipt_email', true ), 'merchant' => get_option( 'admin_email' ) ) as $role => $email ) {
  if ( 'yes' === get_post_meta( $id, '_candy_' . $role . '_sent', true ) ) { continue; }
  if ( wp_mail( $email, 'Candy Corner – Widerruf eingegangen #' . $id, $post->post_content, array( 'Content-Type: text/plain; charset=UTF-8' ) ) ) { update_post_meta( $id, '_candy_' . $role . '_sent', 'yes' ); }
 }
 if ( 'yes' !== get_post_meta( $id, '_candy_customer_sent', true ) || 'yes' !== get_post_meta( $id, '_candy_merchant_sent', true ) ) {
  if ( ! wp_next_scheduled( 'candy_retry_withdrawal', array( $id ) ) ) { wp_schedule_single_event( time() + 300, 'candy_retry_withdrawal', array( $id ) ); }
 }
}
add_action( 'candy_retry_withdrawal', 'candy_deliver_withdrawal' );
add_action( 'admin_notices', function() {
 if ( ! current_user_can( 'manage_woocommerce' ) ) { return; }
 $failed = get_posts( array( 'post_type' => 'candy_withdrawal', 'post_status' => 'private', 'numberposts' => 1, 'meta_query' => array( 'relation' => 'OR', array( 'key' => '_candy_customer_sent', 'value' => 'no' ), array( 'key' => '_candy_merchant_sent', 'value' => 'no' ) ) ) );
 if ( $failed ) { echo '<div class="notice notice-error"><p><strong>Widerruf gespeichert, E-Mail-Versand offen.</strong> Bitte unter WooCommerce → Widerrufe prüfen und die Eingangsbestätigung unverzüglich zustellen. SMTP und WP-Cron prüfen.</p></div>'; }
} );
