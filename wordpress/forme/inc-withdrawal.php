add_shortcode( 'candy_withdrawal', function() {
 $stage = 'enter'; $error = ''; $values = array( 'name' => '', 'contract' => '', 'email' => '' );
 $token = wp_generate_uuid4(); $id = 0;
 if ( 'POST' === ( $_SERVER['REQUEST_METHOD'] ?? '' ) && isset( $_POST['candy_withdrawal_stage'] ) ) {
  try {
   $nonce = isset( $_POST['_wpnonce'] ) && is_string( $_POST['_wpnonce'] ) ? wp_unslash( $_POST['_wpnonce'] ) : '';
   if ( ! wp_verify_nonce( $nonce, 'candy_withdrawal' ) ) { throw new Exception( 'Das Formular ist abgelaufen. Bitte gib deine Daten erneut ein.' ); }
   $values = candy_withdrawal_fields( array( 'name' => wp_unslash( $_POST['withdrawal_name'] ?? '' ), 'contract' => wp_unslash( $_POST['withdrawal_contract'] ?? '' ), 'email' => wp_unslash( $_POST['withdrawal_email'] ?? '' ) ) );
   $token = isset( $_POST['token'] ) && is_string( $_POST['token'] ) ? sanitize_text_field( wp_unslash( $_POST['token'] ) ) : '';
   $signature = isset( $_POST['signature'] ) && is_string( $_POST['signature'] ) ? wp_unslash( $_POST['signature'] ) : '';
   if ( ! hash_equals( hash_hmac( 'sha256', $token, wp_salt() ), $signature ) ) { throw new Exception( 'Bitte öffne das Formular erneut.' ); }
   if ( 'confirm' === $_POST['candy_withdrawal_stage'] ) { $id = candy_record_withdrawal( $values, $token ); $stage = 'done'; } else { $stage = 'review'; }
  } catch ( Exception $e ) { $error = $e->getMessage(); $token = wp_generate_uuid4(); }
 }
 ob_start();
 echo '<div class="candy-withdrawal-form">';
 if ( $error ) { echo '<p role="alert">' . esc_html( $error ) . '</p>'; }
 if ( 'done' === $stage ) {
  echo '<h2>Dein Widerruf ist eingegangen.</h2><p>Referenz: ' . absint( $id ) . ' · ' . esc_html( get_post_meta( $id, '_candy_receipt_time', true ) ) . '</p>';
  echo '<p>' . ( 'yes' === get_post_meta( $id, '_candy_customer_sent', true ) ? 'Die Eingangsbestätigung wurde zum E-Mail-Versand übergeben. Bitte prüfe auch deinen Spam-Ordner.' : 'Deine Erklärung ist gespeichert. Der E-Mail-Versand konnte noch nicht abgeschlossen werden; wir versuchen ihn erneut. Du musst den Widerruf nicht erneut absenden.' ) . '</p><pre>' . esc_html( get_post_field( 'post_content', $id ) ) . '</pre>';
 } else {
  echo '<form method="post">'; wp_nonce_field( 'candy_withdrawal' );
  echo '<input type="hidden" name="token" value="' . esc_attr( $token ) . '"><input type="hidden" name="signature" value="' . esc_attr( hash_hmac( 'sha256', $token, wp_salt() ) ) . '">';
  if ( 'review' === $stage ) { echo '<h2>Widerruf prüfen</h2><p>Hiermit widerrufe ich den folgenden Vertrag bzw. die angegebenen Artikel.</p>'; }
  foreach ( array( 'name' => 'Vor- und Nachname', 'contract' => 'Bestellnummer oder andere Vertragsangabe; bei Teilwiderruf die Artikel', 'email' => 'E-Mail-Adresse für die Eingangsbestätigung' ) as $key => $label ) {
   echo '<label for="withdraw-' . esc_attr( $key ) . '">' . esc_html( $label ) . '</label>';
   $readonly = 'review' === $stage ? ' readonly' : '';
   if ( 'contract' === $key ) { echo '<textarea id="withdraw-contract" name="withdrawal_contract" rows="4" maxlength="2000" required' . $readonly . '>' . esc_textarea( $values[$key] ) . '</textarea>'; }
   else { echo '<input id="withdraw-' . esc_attr( $key ) . '" name="withdrawal_' . esc_attr( $key ) . '" type="' . ( 'email' === $key ? 'email' : 'text' ) . '" maxlength="' . ( 'email' === $key ? '254' : '150' ) . '" autocomplete="' . esc_attr( $key ) . '" value="' . esc_attr( $values[$key] ) . '" required' . $readonly . '>'; }
  }
  echo '<input type="hidden" name="candy_withdrawal_stage" value="' . ( 'review' === $stage ? 'confirm' : 'review' ) . '"><button class="button primary" type="submit">' . ( 'review' === $stage ? 'Widerruf bestätigen' : 'Vertrag widerrufen' ) . '</button>';
  if ( 'review' === $stage ) { echo '<p>Prüfe deine Angaben vor dem Absenden. Über die Zurück-Funktion deines Browsers kannst du sie bearbeiten.</p>'; }
  echo '</form>';
 }
 echo '</div>'; return ob_get_clean();
} );
